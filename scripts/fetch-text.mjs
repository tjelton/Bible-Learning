// Downloads a book's full text (World English Bible, public domain) from
// bible-api.com and writes it to js/data/text-<book>.js for offline use.
//
// Usage: node scripts/fetch-text.mjs Matthew 28
import { writeFile } from "node:fs/promises";

const [book, chapterCount] = [process.argv[2], Number(process.argv[3])];
if (!book || !chapterCount) {
  console.error("Usage: node scripts/fetch-text.mjs <Book> <chapterCount>");
  process.exit(1);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const chapters = {};

for (let c = 1; c <= chapterCount; c++) {
  const url = `https://bible-api.com/${encodeURIComponent(book)}+${c}?translation=web`;
  let json;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url);
    if (res.ok) { json = await res.json(); break; }
    console.error(`  ${res.status} on ${book} ${c}, retrying…`);
    await sleep(5000 * (attempt + 1));
  }
  if (!json) throw new Error(`Failed to fetch ${book} ${c}`);
  chapters[c] = json.verses.map((v) => {
    if (v.chapter !== c) throw new Error(`Unexpected chapter in ${book} ${c}`);
    return v.text.replace(/\s+/g, " ").trim();
  });
  console.error(`${book} ${c}: ${chapters[c].length} verses`);
  await sleep(2500); // bible-api.com allows ~15 requests / 30s
}

const out =
  `// ${book} — World English Bible (public domain). Generated by scripts/fetch-text.mjs.\n` +
  `// TEXT.${book}[chapter][verse - 1] = verse text\n` +
  `window.BIBLE_TEXT = window.BIBLE_TEXT || {};\n` +
  `window.BIBLE_TEXT[${JSON.stringify(book)}] = ${JSON.stringify(chapters)};\n`;
await writeFile(new URL(`../js/data/text-${book.toLowerCase()}.js`, import.meta.url), out);
console.error("done");
