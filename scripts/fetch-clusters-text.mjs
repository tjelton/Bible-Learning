// Downloads the verses Clusters cites (World English Bible, public
// domain) from bible-api.com and writes them to js/data/clusters-text.js, so
// the game can show each word's passage offline. Whole chapters are cached in
// .cache/web/, so only chapters not fetched before are downloaded.
//
// Usage: node scripts/fetch-clusters-text.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import vm from "node:vm";

const require = createRequire(import.meta.url);
const C = require("../js/clusters-engine.js");
const root = new URL("../", import.meta.url);
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(readFileSync(new URL("js/data/clusters.js", root), "utf8"), ctx);

const REF = /^((?:[123] )?[A-Za-z ]+?) (\d+):(\d+)(?:-(\d+))?$/;
const refs = new Set([
  ...ctx.window.CLUSTERS.flatMap((g) => g.items.map((it) => it[1])),
  ...C.RANKS.map((r) => r.ref),
]);

// bible-api.com reads "Jude 1" as verse 1, so books with one chapter are asked
// for every verse by number.
const ONE_CHAPTER = { Obadiah: 21, Philemon: 25, "2 John": 13, "3 John": 14, Jude: 25 };

const cacheDir = new URL(".cache/web/", root);
mkdirSync(cacheDir, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function chapter(book, ch) {
  const file = new URL(`${book.replace(/ /g, "_")}_${ch}.json`, cacheDir);
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const passage = ONE_CHAPTER[book] ? `${book} ${ch}:1-${ONE_CHAPTER[book]}` : `${book} ${ch}`;
  const url = `https://bible-api.com/${encodeURIComponent(passage)}?translation=web`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url);
    if (res.ok) {
      const json = await res.json();
      const verses = json.verses.map((v) => {
        if (v.chapter !== ch) throw new Error(`Unexpected chapter in ${book} ${ch}`);
        return v.text.replace(/\s+/g, " ").trim();
      });
      writeFileSync(file, JSON.stringify(verses));
      console.error(`${book} ${ch}: ${verses.length} verses`);
      await sleep(2500); // bible-api.com allows ~15 requests / 30s
      return verses;
    }
    if (res.status === 404) throw new Error(`Not found: ${book} ${ch}`);
    console.error(`  ${res.status} on ${book} ${ch}, retrying…`);
    await sleep(5000 * (attempt + 1));
  }
  throw new Error(`Failed to fetch ${book} ${ch}`);
}

const out = {};
const problems = [];
for (const ref of [...refs].sort()) {
  const m = REF.exec(ref);
  if (!m) { problems.push(`Can't read reference "${ref}"`); continue; }
  const [book, ch, a, b] = [m[1], +m[2], +m[3], +(m[4] || m[3])];
  let verses;
  try { verses = await chapter(book, ch); } catch (e) { problems.push(`${ref}: ${e.message}`); continue; }
  if (!(a >= 1 && b >= a && b <= verses.length)) { problems.push(`${ref}: verses out of range (chapter has ${verses.length})`); continue; }
  out[ref] = verses.slice(a - 1, b);
}

const file =
  `// Verses cited by Clusters — World English Bible (public domain).\n` +
  `// Generated by scripts/fetch-clusters-text.mjs.\n` +
  `// CLUSTERS_TEXT["Book ch:v-v"] = [text of each verse in the passage]\n` +
  `window.CLUSTERS_TEXT = ${JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"')};\n`;
writeFileSync(new URL("js/data/clusters-text.js", root), file);
console.error(`${Object.keys(out).length} passages written`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
