// Downloads the verses each whole-Bible game cites (World English Bible, public
// domain) from bible-api.com and writes them to that game's js/data/<game>-text.js,
// so it can show each passage offline. Whole chapters are cached in .cache/web/,
// so only chapters not fetched before are downloaded.
//
// Usage: node scripts/fetch-verses.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import vm from "node:vm";

const require = createRequire(import.meta.url);
const root = new URL("../", import.meta.url);

// Each game: its data file and global, the references it cites, and where its
// verses go (file and global).
const GAMES = [
  {
    name: "Clusters and Odd One Out", data: "clusters.js", global: "CLUSTERS", out: "clusters-text.js", outGlobal: "CLUSTERS_TEXT",
    refs: (groups) => [
      ...groups.flatMap((g) => g.items.map((it) => it[1])),
      ...require("../js/clusters-engine.js").RANKS.map((r) => r.ref),
      ...require("../js/odd-one-out-engine.js").RANKS.map((r) => r.ref),
    ],
  },
  {
    name: "Number Crunch", data: "number-crunch.js", global: "NUMBER_CRUNCH", out: "number-crunch-text.js", outGlobal: "NUMBER_CRUNCH_TEXT",
    refs: (facts) => [...facts.map((f) => f.ref), ...require("../js/number-crunch-engine.js").RANKS.map((r) => r.ref)],
  },
  {
    name: "Before or After?", data: "before-or-after.js", global: "BEFORE_OR_AFTER", out: "before-or-after-text.js", outGlobal: "BEFORE_OR_AFTER_TEXT",
    refs: (eras) => [...eras.flatMap((era) => era.events.map((e) => e.ref)), ...require("../js/before-or-after-engine.js").RANKS.map((r) => r.ref)],
  },
];

const REF = /^((?:[123] )?[A-Za-z ]+?) (\d+):(\d+)(?:-(\d+))?$/;

// bible-api.com reads "Jude 1" as verse 1, so books with one chapter are asked
// for every verse by number.
const ONE_CHAPTER = { Obadiah: 21, Philemon: 25, "2 John": 13, "3 John": 14, Jude: 25 };

const cacheDir = new URL(".cache/web/", root);
mkdirSync(cacheDir, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function chapter(book, ch) {
  const file = new URL(`${book.replace(/ /g, "_")}_${ch}.json`, cacheDir);
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const passage = ONE_CHAPTER[book] ? `${book} ${ch}:1-${ONE_CHAPTER[book]}` : `${book} ${ch}`;
  const url = `https://bible-api.com/${encodeURIComponent(passage)}?translation=web`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url);
    if (res.ok) {
      const json = await res.json();
      const verses = json.verses.map((v) => {
        if (v.chapter !== ch) throw new Error(`Unexpected chapter in ${book} ${ch}`);
        return v.text.replace(/\s+/g, " ").trim();
      });
      writeFileSync(file, JSON.stringify(verses));
      console.error(`${book} ${ch}: ${verses.length} verses`);
      await sleep(2500); // bible-api.com allows ~15 requests / 30s
      return verses;
    }
    if (res.status === 404) throw new Error(`Not found: ${book} ${ch}`);
    console.error(`  ${res.status} on ${book} ${ch}, retrying…`);
    await sleep(5000 * (attempt + 1));
  }
  throw new Error(`Failed to fetch ${book} ${ch}`);
}

const problems = [];
for (const game of GAMES) {
  const dataFile = new URL(`js/data/${game.data}`, root);
  if (!existsSync(dataFile)) continue;
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(readFileSync(dataFile, "utf8"), ctx);
  const out = {};
  for (const ref of [...new Set(game.refs(ctx.window[game.global]))].sort()) {
    const m = REF.exec(ref);
    if (!m) { problems.push(`${game.name}: can't read reference "${ref}"`); continue; }
    const [book, ch, a, b] = [m[1], +m[2], +m[3], +(m[4] || m[3])];
    let verses;
    try { verses = await chapter(book, ch); } catch (e) { problems.push(`${game.name}: ${ref}: ${e.message}`); continue; }
    if (!(a >= 1 && b >= a && b <= verses.length)) { problems.push(`${game.name}: ${ref}: verses out of range (chapter has ${verses.length})`); continue; }
    out[ref] = verses.slice(a - 1, b);
  }
  const file =
    `// Verses cited by ${game.name} — World English Bible (public domain).\n` +
    `// Generated by scripts/fetch-verses.mjs.\n` +
    `// ${game.outGlobal}["Book ch:v-v"] = [text of each verse in the passage]\n` +
    `window.${game.outGlobal} = ${JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"')};\n`;
  writeFileSync(new URL(`js/data/${game.out}`, root), file);
  console.error(`${game.name}: ${Object.keys(out).length} passages written to js/data/${game.out}`);
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
